def explain_prediction(pipeline, row_df, top_n=6):
    prep = pipeline.named_steps["prep"]
    model = pipeline.named_steps["model"]
    X_trans = prep.transform(row_df[feature_cols])
    feat_names = [n.replace("cat__", "").replace("num__", "") for n in prep.get_feature_names_out()]
    explainer = shap.TreeExplainer(model)
    shap_values = explainer.shap_values(X_trans).reshape(-1)
    return sorted(zip(feat_names, shap_values), key=lambda p: abs(p[1]), reverse=True)[:top_n]

