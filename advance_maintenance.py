RISK_TIERS = [
    (0.80, "Critical", "Schedule corrective maintenance immediately - treat as a near-term failure risk."),
    (0.55, "High", "Plan predictive maintenance within the next cycle and monitor closely until then."),
    (0.30, "Medium", "Keep on the normal preventive schedule; re-check at the next snapshot."),
    (0.00, "Low", "No action needed beyond routine preventive maintenance."),
]

def risk_tier(score):
    for threshold, label, action in RISK_TIERS:
        if score >= threshold:
            return label, action
    return RISK_TIERS[-1][1], RISK_TIERS[-1][2]

def predict_batch(df, reference_stats):
    clean_df, quality_report, issues_summary = validate_and_clean(df, reference_stats)
    X = clean_df[feature_cols]

    results = clean_df.copy()
    results["predicted_maintenance_type"] = clf_pipeline.predict(X)
    proba = clf_pipeline.predict_proba(X)
    results["predicted_maintenance_type_confidence"] = proba.max(axis=1).round(3)

    risk_scores = risk_pipeline.predict(X).clip(0, 1)
    results["predicted_failure_risk_score"] = risk_scores.round(3)
    tiers = [risk_tier(s) for s in risk_scores]
    results["risk_tier"] = [t[0] for t in tiers]
    results["recommended_action"] = [t[1] for t in tiers]

    results["predicted_remaining_useful_life_days"] = rul_pipeline.predict(X).round().astype(int).clip(min=0)
    results["predicted_days_until_due"] = due_pipeline.predict(X).round().astype(int)

    return results, quality_report, issues_summary

