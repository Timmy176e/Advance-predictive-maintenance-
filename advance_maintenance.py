def append_to_log(results_df):
    out = results_df.copy()
    out["logged_at"] = pd.Timestamp.now().isoformat()
    out = out.reindex(columns=LOG_COLUMNS)
    out.to_csv(LOG_PATH, mode="a", header=not os.path.exists(LOG_PATH), index=False)
    return len(out)

def read_log():
    if not os.path.exists(LOG_PATH):
        return pd.DataFrame(columns=LOG_COLUMNS)
    log_df = pd.read_csv(LOG_PATH)
    for c in ("snapshot_date", "logged_at"):
        if c in log_df.columns:
            log_df[c] = pd.to_datetime(log_df[c], errors="coerce")
    return log_df

def numeric_drift_table(df, reference_stats):
    rows = []
    for col in numeric_features:
        stats = reference_stats["numeric_stats"][col]
        train_std = stats["std"] or 1e-6
        batch_mean = float(df[col].mean())
        shift = (batch_mean - stats["mean"]) / train_std
        rows.append({
            "feature": col, "train_mean": stats["mean"], "batch_mean": round(batch_mean, 4),
            "shift_in_std_devs": round(shift, 2), "flag": "drift" if abs(shift) > 1.0 else "ok",
        })
    return pd.DataFrame(rows)

